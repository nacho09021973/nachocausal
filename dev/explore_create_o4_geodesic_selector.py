"""dev exploration — cheap refutation test of a selector R(C) proposed by CREATE.

NOT sealed. DEV_SEEDS only; never imports or evaluates VALIDATION_SEEDS. Does not
modify the sealed estimator, the generator or any threshold: it only reads
`generator` and `thresholds` so the clouds match the frozen baseline.

Origin: route O4 from the CREATE tool test of 2026-10-16
(~/herramientas/CREATE/runs/2026-10-16-selector-rc/, generated by claude-opus-5-5,
UNVERIFIED). Question open in README.md:444 and dev/PR003_C1_RELATIONAL_SPEC.md §8.
Related precedent: the sealed observable O is the future height of minimal
elements (dev/explore_observable.py:9); O4 is its time-dual used as a selector.

Rule (order-only, relabel-invariant):
  h(x)      = number of elements in the longest chain ending at x
  Hgt       = max_x h(x)
  R(C)      = { m in Max(C) : h(m) >= (1 - eps) * Hgt }      (endpoints of
              near-longest chains; any such chain extends to a maximal element)
  A = down(R), B = C \\ A, interface = cover links (x, y), x in A, y in B.

The hidden embedding only SCORES (fraction of B and of interface heads with
r < R_S); it never enters the rule.

Kinds, on one identical point cloud per seed:
  BH      sealed box, Schwarzschild EF causality (box straddles r = R_S)
  MINK    same cloud, flat causality
  BH_EXT  same cloud shifted by +R_SHIFT in r: all points outside R_S, curved but
          no horizon in the box. Separates "horizon" from "curvature / tilt".

PRE-DECLARED decision (written before the first run; primary eps = 0.1, medians
over DEV_SEEDS, each intensity separately):
  REFUTED if, at ANY intensity,
    (F1) BH: median fraction of B with r < R_S < 0.8              (B not interior), or
    (F2) MINK: median |B|/N >= 0.5 * BH median |B|/N             (flat gives same), or
    (F3) BH_EXT: median |B|/N >= 0.5 * BH median |B|/N           (curvature, not horizon)
  or if the relabel guard fails.
  Otherwise SURVIVES_CHEAP_TEST. Surviving is NOT confirmation: one geometry,
  one box, dev seeds; thresholds 0.8 / 0.5 are fixed by hand, not principled.
eps 0.05 and 0.2 are reported as secondary, not used for the decision.

Run:  .venv/bin/python dev/explore_create_o4_geodesic_selector.py
Writes dev/explore_create_o4_geodesic_selector_results.json (refuses to overwrite).
"""

from __future__ import annotations

import json
import os
import subprocess
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from nachocausal import generator, thresholds  # noqa: E402

R_S = thresholds.R_S
INTENSITIES = (1500.0, 3000.0)
EPS_PRIMARY = 0.1
EPS_ALL = (0.05, 0.1, 0.2)
R_SHIFT = 0.8
F1_MIN_INTERIOR = 0.8
F23_MAX_RATIO = 0.5
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "explore_create_o4_geodesic_selector_results.json")


def heights(C: np.ndarray) -> np.ndarray:
    """Longest-chain length ending at each element. C[i, j] = j precedes i.
    Past cardinality is strictly increasing along the order, so sorting by it
    is a linear extension computed from the order alone."""
    order = np.argsort(C.sum(axis=1), kind="stable")
    h = np.zeros(C.shape[0], dtype=np.int64)
    for i in order:
        past = C[i]
        h[i] = 1 + (h[past].max() if past.any() else 0)
    return h


def select(C: np.ndarray, eps: float, h: np.ndarray):
    maximal = ~C.any(axis=0)                     # nothing has i in its past
    R = maximal & (h >= (1.0 - eps) * h.max())
    A = R | C[R].any(axis=0)                     # down(R)
    B = ~A
    Ci = C.astype(np.float32)
    between = (Ci @ Ci) > 0                      # [y, x]: some z with x < z < y
    cover = C & ~between                         # [y, x]: x is covered by y
    links = np.argwhere(cover & B[:, None] & A[None, :])   # rows (y, x)
    return R, A, B, links


def relabel_guard(C: np.ndarray, eps: float, seed: int) -> bool:
    perm = np.random.default_rng(seed).permutation(C.shape[0])
    Cp = C[np.ix_(perm, perm)]
    R, _, B, links = select(C, eps, heights(C))
    Rp, _, Bp, linksp = select(Cp, eps, heights(Cp))
    same_R = np.array_equal(Rp, R[perm])
    same_B = np.array_equal(Bp, B[perm])
    pairs = {(int(perm[y]), int(perm[x])) for y, x in linksp}
    return bool(same_R and same_B and pairs == {(int(y), int(x)) for y, x in links})


def measure(C, r, eps, h):
    R, _, B, links = select(C, eps, h)
    n = C.shape[0]
    nb = int(B.sum())
    interior = r < R_S
    return {
        "N": n, "height": int(h.max()), "n_R": int(R.sum()), "n_max": int((~C.any(axis=0)).sum()),
        "B_frac": nb / n,
        "B_interior_frac": (float(interior[B].mean()) if nb else None),
        "interior_in_B_frac": (float(B[interior].mean()) if interior.any() else None),
        "n_interface": int(len(links)),
        "interface_head_interior_frac": (float(interior[links[:, 0]].mean()) if len(links) else None),
    }


def median(values):
    v = [x for x in values if x is not None]
    return float(np.median(v)) if v else None


def main() -> int:
    if os.path.exists(OUT):
        print(f"refusing to overwrite {OUT}", file=sys.stderr)
        return 1
    assert set(thresholds.DEV_SEEDS).isdisjoint(thresholds.VALIDATION_SEEDS)
    rows = []
    for intensity in INTENSITIES:
        for seed in thresholds.DEV_SEEDS:
            pts, _, _ = generator.numpy_sprinkle(seed, intensity)
            shifted = pts + np.array([0.0, R_SHIFT])
            for kind, cloud, causal in (("BH", pts, "BH"), ("MINK", pts, "MINK"), ("BH_EXT", shifted, "BH")):
                C = generator.past_matrix_fast(cloud, causal)
                h = heights(C)
                for eps in EPS_ALL:
                    row = {"kind": kind, "intensity": intensity, "seed": seed, "eps": eps}
                    row.update(measure(C, cloud[:, 1], eps, h))
                    rows.append(row)
            print(f"done intensity={intensity:.0f} seed={seed}", flush=True)
    C0 = generator.past_matrix_fast(generator.numpy_sprinkle(thresholds.DEV_SEEDS[0], INTENSITIES[0])[0], "BH")
    guard = relabel_guard(C0, EPS_PRIMARY, seed=1)

    summary, reasons = {}, []
    for intensity in INTENSITIES:
        for eps in EPS_ALL:
            cell = {}
            for kind in ("BH", "MINK", "BH_EXT"):
                sel = [x for x in rows if x["kind"] == kind and x["intensity"] == intensity and x["eps"] == eps]
                cell[kind] = {k: median([x[k] for x in sel]) for k in
                              ("N", "n_R", "n_max", "B_frac", "B_interior_frac", "interior_in_B_frac",
                               "n_interface", "interface_head_interior_frac")}
            summary[f"{intensity:.0f}/eps={eps}"] = cell
            if eps != EPS_PRIMARY:
                continue
            bh, mk, ext = cell["BH"], cell["MINK"], cell["BH_EXT"]
            if bh["B_interior_frac"] is None or bh["B_interior_frac"] < F1_MIN_INTERIOR:
                reasons.append(f"F1 at {intensity:.0f}: BH B_interior_frac={bh['B_interior_frac']}")
            if bh["B_frac"] == 0 or mk["B_frac"] >= F23_MAX_RATIO * bh["B_frac"]:
                reasons.append(f"F2 at {intensity:.0f}: MINK B_frac={mk['B_frac']} vs BH {bh['B_frac']}")
            if bh["B_frac"] == 0 or ext["B_frac"] >= F23_MAX_RATIO * bh["B_frac"]:
                reasons.append(f"F3 at {intensity:.0f}: BH_EXT B_frac={ext['B_frac']} vs BH {bh['B_frac']}")
    if not guard:
        reasons.append("relabel guard failed")
    verdict = "REFUTED" if reasons else "SURVIVES_CHEAP_TEST"
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True,
                            cwd=os.path.dirname(OUT)).stdout.strip()
    result = {"verdict": verdict, "reasons": reasons, "relabel_guard": guard, "repo_head": commit,
              "eps_primary": EPS_PRIMARY, "r_shift": R_SHIFT, "seeds": list(thresholds.DEV_SEEDS),
              "summary_medians": summary, "rows": rows}
    with open(OUT, "x") as f:
        json.dump(result, f, indent=1)
    print(json.dumps({"verdict": verdict, "reasons": reasons, "relabel_guard": guard,
                      "summary_medians": summary}, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
